package org.telegram.ui.Components;

/**
 * NativeDo stub of org.telegram.ui.Components.Point — a pair of floats used by
 * gesture / vector rendering. Mirrors upstream field names ({@code x}, {@code y}).
 */
public class Point {
    public float x;
    public float y;

    public Point() {
    }

    public Point(float x, float y) {
        this.x = x;
        this.y = y;
    }
}
